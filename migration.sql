-- Миграция рабочей БД (без пересоздания): тип билета привязывается к типу места,
-- цена фиксируется в билете. Выполнять один раз: psql -d tickets -f migration.sql
-- Всё в одной транзакции: при любой ошибке изменения откатываются.
BEGIN;

-- 1. Тип билета -> для каких мест он действует
ALTER TABLE "Тип_Билета" ADD COLUMN "Тип_Места" VARCHAR(50);

-- У всех типов билетов название совпадает с типом места, кроме типов 2 и 7:
-- они назывались «Стандарт», но продавались на места «Партер»
UPDATE "Тип_Билета" SET "Название" = 'Партер' WHERE "id_Типа" IN (2, 7);
UPDATE "Тип_Билета" SET "Тип_Места" = "Название";

ALTER TABLE "Тип_Билета" ALTER COLUMN "Тип_Места" SET NOT NULL;
ALTER TABLE "Тип_Билета"
  ADD CONSTRAINT ticket_types_event_seat_type_key UNIQUE ("id_Мероприятия", "Тип_Места");

-- 2. Цена в билете: копируем текущую цену типа билета
ALTER TABLE "Билет" ADD COLUMN "Цена" NUMERIC(10,2);
UPDATE "Билет" b SET "Цена" = t."Цена" FROM "Тип_Билета" t WHERE t."id_Типа" = b."id_Типа";
ALTER TABLE "Билет" ALTER COLUMN "Цена" SET NOT NULL;

-- 3. Проверка: у каждого билета тип места совпадает с типом билета, а мероприятие с мероприятием типа.
--    Если есть расхождения, миграция прерывается и откатывается.
DO $$
DECLARE bad TEXT;
BEGIN
  SELECT string_agg(b."id_Билета"::text, ', ') INTO bad
    FROM "Билет" b
    JOIN "Места"      s ON s."id_Места" = b."id_Места"
    JOIN "Тип_Билета" t ON t."id_Типа"  = b."id_Типа"
   WHERE t."Тип_Места" <> s."Тип_Места" OR t."id_Мероприятия" <> b."id_Мероприятия";
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'Билеты, у которых тип места не совпадает с типом билета: %', bad;
  END IF;
END $$;

COMMIT;
